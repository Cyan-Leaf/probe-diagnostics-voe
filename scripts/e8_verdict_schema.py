"""E8 schema compliance: emit the five top-level keys NEXT_STEPS_AND_DIVISION.md fixed.

Why a separate file rather than editing `E8_verdict.json`: that file is a delivered artifact
produced by `e8_verdict.py`, and the project's first red line is that `results/` numbers are
script-produced, never hand-edited. Rewriting it in place would also break the cross-references
in E8_REPORT.md §14 and in E10_CALIPER-style downstream readers.

So this script *derives* the required shape from the delivered JSON and writes it as
`E8_verdict_schema.json`. Both files then exist: the original keeps its nested detail, and the
schema view satisfies the literal acceptance criterion ("keys present, threshold matches
PREREG.md, every number in the report traceable").

The reference cell is layer 16 / t=600 for both datasets. `note` carries the definitions that
differ per backbone (VP vs flow timestep semantics, random-init rule) because a reader who only
sees this file must not assume the numbers are like-for-like.

Run: python scripts/e8_verdict_schema.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "E8_second_backbone"


def pick(ds: dict, bb: str, key: str):
    return ds["backbones"].get(bb, {}).get(key)


def main():
    src = json.loads((OUT / "E8_verdict.json").read_text())
    threshold = src["d1_threshold"]
    assert threshold == 0.5, f"threshold {threshold} does not match PREREG.md (50%)"

    rows = []
    for ds_name, ds in src["datasets"].items():
        for bb, entry in ds["backbones"].items():
            cell = entry.get("L16|t600")
            d2 = entry.get("d2")
            if not cell or not d2:
                continue
            rows.append({
                "dataset": ds_name,
                "model": bb,
                "reference_cell": {"layer": cell["layer"], "t": cell["timestep"]},
                "lower_bounds": {
                    "raw_pixel": entry.get("raw_pixel", {}).get("auc"),
                    "vae_latent": entry.get("vae_latent", {}).get("auc"),
                    "random_dit": cell["auc_random"],
                    "trained_dit": cell["auc_real"],
                },
                # A cell can be below threshold AND uninterpretable (LTX). Reporting it as
                # "fail" would turn a non-measurement into evidence, so it gets its own label
                # here exactly as it does in E8_REPORT.md §14.3 / §15.2.
                "d1": {"training_share": cell["d1_training_share"],
                       "verdict": ("NOT interpretable" if not cell["interpretable"]
                                   else cell["verdict"]),
                       "threshold": threshold,
                       "interpretable": bool(cell["interpretable"]),
                       "why": cell.get("note") or (
                           "" if cell["interpretable"] else "see E8_REPORT.md §14.3")},
                "d2": {"auc_physics": d2["auc_physics"],
                       "auc_appearance": d2["auc_appearance"],
                       "gap": d2["gap"],
                       "verdict": d2["verdict"]},
            })

    out = {
        "model": "seven video diffusion transformers; per-row `model` names the one",
        "reference_cell": {"layer": 16, "t": 600},
        "lower_bounds": "per-row, see `rows[*].lower_bounds`",
        "d1": "per-row, see `rows[*].d1`",
        "d2": "per-row, see `rows[*].d2`",
        "note": (
            "This file is a schema view of E8_verdict.json, generated by "
            "scripts/e8_verdict_schema.py. It exists because E8_verdict.json predates the "
            "key list fixed in NEXT_STEPS_AND_DIVISION.md §1 and carries the same numbers in "
            "a nested layout. Nothing was recomputed. Two things must not be lost when "
            "quoting it: (1) `t=600` is a flow-matching sigma of 0.600 on Wan/LTX/Mochi but "
            "97.7% noise on the VP models CogVideoX-2b/5b, whose SNR-matched cell is t=298 "
            "and is reported in E8_verdict.json; (2) the random-DiT lower bound uses a "
            "norm-aware initialisation on CogVideoX/LTX/Mochi/Wan2.1 because the Wan2.2 rule "
            "collapses affine-norm blocks to a constant, so random-DiT values are comparable "
            "in ordering only, not numerically (see manifest.json deviations[0])."),
        "thresholds_from": src["thresholds_from"],
        "prereg": src["prereg"],
        "rows": sorted(rows, key=lambda r: (r["dataset"], r["model"])),
    }

    dst = OUT / "E8_verdict_schema.json"
    dst.write_text(json.dumps(out, indent=1))
    print(f"{len(rows)} rows -> {dst}")
    for r in out["rows"]:
        print(f"  {r['dataset']:9s} {r['model']:14s} D1 {r['d1']['training_share']*100:5.1f}% "
              f"{r['d1']['verdict']:18s} D2 {r['d2']['verdict']}")


if __name__ == "__main__":
    main()
